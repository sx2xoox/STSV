def logo(company, industry):
    rows = E[company]
    outline, shadow, base, light = BADGES[industry]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y in range(16):
        for x in range(16):
            corner = (x in (0, 15) and y in (0, 1, 14, 15)) or (y in (0, 15) and x in (0, 1, 14, 15))
            if corner:
                continue
            edge = x in (0, 15) or y in (0, 15) or (x in (1, 14) and y in (1, 14))
            if edge:
                px[x, y] = outline + (255,)
            elif x == 1 or y == 1:
                px[x, y] = light + (255,)
            elif x == 14 or y == 14:
                px[x, y] = shadow + (255,)
            else:
                px[x, y] = base + (255,)
    # the emblem, centred: 10 wide, as many rows as drawn (up to 10)
    rows = [r.ljust(10, ".")[:10] for r in rows][:10]
    y0 = 3 + (10 - len(rows)) // 2
    filled = {(x, y) for y, r in enumerate(rows) for x, ch in enumerate(r) if ch != "."}
    # a dark rim under the emblem's lower right edges, so white reads on the light badges too
    for (x, y) in filled:
        for dx, dy in ((1, 0), (0, 1), (1, 1)):
            q = (x + dx, y + dy)
            if q not in filled and 0 <= 3 + q[0] < 15 and 0 <= y0 + q[1] < 15:
                px[3 + q[0], y0 + q[1]] = shadow + (255,)
    for (x, y) in filled:
        ch = rows[y][x]
        c = {"#": WHITE, "s": SHADE, "k": outline, "g": GOLD}[ch]
        px[3 + x, y0 + y] = c + (255,)
    return im


def all_logos(companies):
    """companies: id -> industry (from stocks.yml)."""
    return {f"logo_{cid}": logo(cid, ind) for cid, ind in companies.items() if cid in E}


def companies(pack):
    import yaml
    data = yaml.safe_load((pack / "stocks.yml").read_text(encoding="utf-8"))
    return {cid: c["industry"] for cid, c in data["companies"].items()}


def sheet(path, logos, scale=6):
    names = list(logos)
    cols = 7
    rows = (len(names) + cols - 1) // cols
    out = Image.new("RGBA", (cols * 18 * scale, rows * 18 * scale), (40, 43, 50, 255))
    for k, n in enumerate(names):
        out.alpha_composite(logos[n].resize((16 * scale, 16 * scale), Image.NEAREST), ((k % cols) * 18 * scale + scale, (k // cols) * 18 * scale + scale))
    out.save(path)
